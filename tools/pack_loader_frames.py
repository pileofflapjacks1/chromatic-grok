#!/usr/bin/env python3
"""Pack Carty G loader PNGs into palette + RLE for the Chromatic Grok overlay.

Source frames are 160x144 with a shared 3-color palette. Output is a C file with
one RLE stream per frame (count, index) pairs so firmware can paint horizontal
runs without a full RGB565 scratch buffer.

Usage (from repo root):
  python3 tools/pack_loader_frames.py
"""
from __future__ import annotations

import pathlib
import sys

try:
    from PIL import Image
except ImportError as exc:  # pragma: no cover
    sys.stderr.write("pack_loader_frames.py needs Pillow: %s\n" % exc)
    sys.exit(1)

ROOT = pathlib.Path(__file__).resolve().parents[1]
SRC_DIR = ROOT / "components" / "grok" / "loader"
OUT_C = ROOT / "components" / "grok" / "grok_loader_frames.c"
OUT_H = ROOT / "components" / "grok" / "grok_loader_frames.h"

# Shared palette (RGB), matches Carty G v2 art (near-black / mid-gray / white).
PALETTE = [
    (0x14, 0x14, 0x14),
    (0x46, 0x46, 0x46),
    (0xF5, 0xF5, 0xF5),
]

# Frame hold times from v2/loader.gif (ms).
DURATIONS_MS = (300, 200, 200, 150, 120, 200, 300, 300, 120, 300)
FRAME_COUNT = len(DURATIONS_MS)
WIDTH = 160
HEIGHT = 144


def nearest(rgb: tuple[int, int, int]) -> int:
    best = 0
    best_d = 1 << 30
    for i, p in enumerate(PALETTE):
        d = (rgb[0] - p[0]) ** 2 + (rgb[1] - p[1]) ** 2 + (rgb[2] - p[2]) ** 2
        if d < best_d:
            best_d = d
            best = i
    return best


def rle_encode(indices: list[int]) -> bytes:
    out = bytearray()
    i = 0
    n = len(indices)
    while i < n:
        v = indices[i]
        c = 1
        while i + c < n and indices[i + c] == v and c < 255:
            c += 1
        out.append(c)
        out.append(v)
        i += c
    return bytes(out)


def rgb565(r: int, g: int, b: int) -> int:
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def main() -> int:
    frames: list[bytes] = []
    for i in range(FRAME_COUNT):
        path = SRC_DIR / ("loader_%d.png" % i)
        im = Image.open(path).convert("RGB")
        if im.size != (WIDTH, HEIGHT):
            sys.stderr.write("%s: expected %dx%d, got %s\n" % (path, WIDTH, HEIGHT, im.size))
            return 1
        idxs = [nearest(im.getpixel((x, y))) for y in range(HEIGHT) for x in range(WIDTH)]
        enc = rle_encode(idxs)
        frames.append(enc)
        print("frame %d: %d bytes RLE (%d runs)" % (i, len(enc), len(enc) // 2))

    total = sum(len(f) for f in frames) + len(PALETTE) * 2
    print("total flash payload (RLE + RGB565 palette): %d bytes" % total)
    if total >= 20 * 1024:
        sys.stderr.write("WARNING: flash payload exceeds ~20 KB budget (%d bytes)\n" % total)

    h = []
    h.append("/* Auto-generated by tools/pack_loader_frames.py — do not edit by hand.")
    h.append(" * Source art: components/grok/loader/loader_*.png (Carty G v2, original).")
    h.append(" * SPDX-License-Identifier: GPL-3.0-or-later")
    h.append(" */")
    h.append("#pragma once")
    h.append("")
    h.append("#include <stddef.h>")
    h.append("#include <stdint.h>")
    h.append("")
    h.append("#define GROK_LOADER_WIDTH %d" % WIDTH)
    h.append("#define GROK_LOADER_HEIGHT %d" % HEIGHT)
    h.append("#define GROK_LOADER_FRAME_COUNT %d" % FRAME_COUNT)
    h.append("#define GROK_LOADER_PALETTE_COUNT %d" % len(PALETTE))
    h.append("")
    h.append("typedef struct GrokLoaderFrame {")
    h.append("    const uint8_t *rle; /* (count, index) pairs */")
    h.append("    size_t rle_len;")
    h.append("    uint16_t duration_ms;")
    h.append("} GrokLoaderFrame;")
    h.append("")
    h.append("extern const uint16_t grok_loader_palette_rgb565[GROK_LOADER_PALETTE_COUNT];")
    h.append("extern const uint32_t grok_loader_palette_rgb[GROK_LOADER_PALETTE_COUNT];")
    h.append("extern const GrokLoaderFrame grok_loader_frames[GROK_LOADER_FRAME_COUNT];")
    h.append("")

    OUT_H.write_text("\n".join(h) + "\n", encoding="utf-8")

    c = []
    c.append("/* Auto-generated by tools/pack_loader_frames.py — do not edit by hand.")
    c.append(" * Source art: components/grok/loader/loader_*.png (Carty G v2, original).")
    c.append(" * SPDX-License-Identifier: GPL-3.0-or-later")
    c.append(" */")
    c.append('#include "grok_loader_frames.h"')
    c.append("")
    c.append("const uint16_t grok_loader_palette_rgb565[GROK_LOADER_PALETTE_COUNT] = {")
    for r, g, b in PALETTE:
        c.append("    0x%04x, /* #%02x%02x%02x */" % (rgb565(r, g, b), r, g, b))
    c.append("};")
    c.append("")
    c.append("const uint32_t grok_loader_palette_rgb[GROK_LOADER_PALETTE_COUNT] = {")
    for r, g, b in PALETTE:
        c.append("    0x%06x," % ((r << 16) | (g << 8) | b))
    c.append("};")
    c.append("")

    for i, enc in enumerate(frames):
        c.append("static const uint8_t s_frame_%d[] = {" % i)
        line = "   "
        for j, b in enumerate(enc):
            line += " 0x%02x," % b
            if (j % 12) == 11:
                c.append(line)
                line = "   "
        if line.strip():
            c.append(line)
        c.append("};")
        c.append("")

    c.append("const GrokLoaderFrame grok_loader_frames[GROK_LOADER_FRAME_COUNT] = {")
    for i, enc in enumerate(frames):
        c.append(
            "    { s_frame_%d, sizeof(s_frame_%d), %d },"
            % (i, i, DURATIONS_MS[i])
        )
    c.append("};")
    c.append("")

    OUT_C.write_text("\n".join(c) + "\n", encoding="utf-8")
    print("wrote %s" % OUT_H.relative_to(ROOT))
    print("wrote %s" % OUT_C.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
